// Export the SIP handoff contract (src/sip-handoff-contract.ts) as a standalone
// TypeScript file for a consumer that talks to the gateway's transfer API.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

const output = process.argv[2];
if (!output) throw new Error('Usage: node scripts/export-sip-contract.mjs <output.ts>');
const source = await readFile(new URL('../src/sip-handoff-contract.ts', import.meta.url), 'utf8');
await mkdir(dirname(output), { recursive: true });
await writeFile(output, '// Generated by scripts/export-sip-contract.mjs. Do not edit.\n' + source);
